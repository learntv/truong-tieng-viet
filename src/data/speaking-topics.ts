import type { SpeakingSentence } from "@/lib/speech";

// Curated speaking-practice topics for /luyen-noi, alongside the ones derived
// from lesson content. Written for kids aged 5–12: short sentences (2–10 words),
// everyday vocabulary, positive tone. Ids are prefixed "noi-" so they can never
// collide with curriculum chude ids in the /luyen-noi/$chuDeId param.

export type StaticSpeakingTopic = {
  id: string;
  title: string;
  emoji: string;
  sentences: string[];
};

export function staticTopicSentences(topic: StaticSpeakingTopic): SpeakingSentence[] {
  return topic.sentences.map((text, i) => ({ id: `${topic.id}#${i}`, text }));
}

